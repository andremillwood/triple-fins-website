create extension if not exists "uuid-ossp";

alter table public.registrations
  add column if not exists registration_status text not null default 'new',
  add column if not exists preferred_session text,
  add column if not exists consent_at timestamptz,
  add column if not exists payment_method text not null default 'pay_on_site',
  add column if not exists payment_provider text,
  add column if not exists payment_reference text,
  add column if not exists amount_jmd numeric(10,2),
  add column if not exists updated_at timestamptz not null default now();

alter table public.registrations drop constraint if exists registrations_payment_status_check;
alter table public.registrations add constraint registrations_payment_status_check
  check (payment_status in ('pending','manual_verification','paid','waived','cancelled'));
alter table public.registrations add constraint registrations_registration_status_check
  check (registration_status in ('new','confirmed','attended','cancelled'));
alter table public.registrations add constraint registrations_payment_method_check
  check (payment_method in ('stripe','bank_transfer','pay_on_site'));

create table if not exists public.staff_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin','staff')),
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default uuid_generate_v4(),
  customer_name text not null,
  email text not null,
  phone text not null,
  subtotal_jmd numeric(10,2) not null check (subtotal_jmd >= 0),
  payment_method text not null check (payment_method in ('stripe','bank_transfer','pay_on_pickup')),
  payment_status text not null default 'pending' check (payment_status in ('pending','manual_verification','paid','waived','cancelled')),
  payment_provider text,
  payment_reference text,
  fulfillment_method text not null check (fulfillment_method in ('pickup','delivery_coordination')),
  fulfillment_status text not null default 'new' check (fulfillment_status in ('new','coordinating','ready','fulfilled','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default uuid_generate_v4(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid not null references public.products(id),
  product_name text not null,
  quantity integer not null check (quantity between 1 and 20),
  unit_price_jmd numeric(10,2) not null check (unit_price_jmd >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null check (event_name in ('program_cta_clicked','registration_started','registration_completed','order_started','order_completed','inquiry_submitted')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists registrations_created_at_idx on public.registrations(created_at desc);
create index if not exists registrations_status_idx on public.registrations(registration_status, payment_status);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
create index if not exists inquiries_created_at_idx on public.inquiries(created_at desc);

alter table public.staff_roles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.analytics_events enable row level security;

drop policy if exists "Allow authenticated read inquiries" on public.inquiries;
drop policy if exists "Staff read inquiries" on public.inquiries;
create policy "Staff read inquiries" on public.inquiries for select to authenticated
using (exists (select 1 from public.staff_roles where user_id = auth.uid()));
drop policy if exists "Staff update inquiries" on public.inquiries;
create policy "Staff update inquiries" on public.inquiries for update to authenticated
using (exists (select 1 from public.staff_roles where user_id = auth.uid()))
with check (exists (select 1 from public.staff_roles where user_id = auth.uid()));

drop policy if exists "Staff access registrations" on public.registrations;
create policy "Staff access registrations" on public.registrations for all to authenticated
using (exists (select 1 from public.staff_roles where user_id = auth.uid()))
with check (exists (select 1 from public.staff_roles where user_id = auth.uid()));

create policy "Read own staff role" on public.staff_roles for select to authenticated using (user_id = auth.uid());
create policy "Staff access orders" on public.orders for all to authenticated
using (exists (select 1 from public.staff_roles where user_id = auth.uid()))
with check (exists (select 1 from public.staff_roles where user_id = auth.uid()));
create policy "Staff access order items" on public.order_items for select to authenticated
using (exists (select 1 from public.staff_roles where user_id = auth.uid()));

-- Public writes go through validated server routes using the service role.
drop policy if exists "Allow public insert to inquiries" on public.inquiries;
drop policy if exists "Allow public insert to registrations" on public.registrations;
